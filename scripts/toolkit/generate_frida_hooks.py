#!/usr/bin/env python3
"""
generate_frida_hooks.py — Print (or save) a Frida hooks JavaScript file
for runtime analysis of the WE Android app (package
io.wallpaperengine.weclient).

The generated script hooks:
  - TcpClient.performAuthentication / connect / disconnect
  - TcpClient$EncAuthRequest / EncAuthResponse (constructor + setters)
  - DiscoverService.beginDiscovery / endDiscovery
  - TransferService.beginPairing / sendPin
  - javax.crypto.Cipher.init + doFinal (all AES operations)
  - RSAPublicKeyHelper.setModulus / setExponent
  - SceneLib.getWallpaperType / getWallpaperFileVirtualOffset (native JNI)
  - SupportFileLoader.loadBitmapFromVFS / loadDataFromUri

USAGE
=====
    python generate_frida_hooks.py                  # print to stdout
    python generate_frida_hooks.py --out hooks.js  # save to file
    python generate_frida_hooks.py --help

Then run on a phone with the WE Android app installed and a Frida server:
    frida -U -f io.wallpaperengine.weclient -l hooks.js
    frida -U -n weclient -l hooks.js    # attach to running process

DEPENDENCIES
============
    pip install frida-tools  (provides the `frida` CLI)
    A Frida server running on the phone (matching version).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HOOK_JS = """// === WE Android Frida Hooks ===
// Auto-generated by generate_frida_hooks.py
// Hooks for the Wallpaper Engine Android app (io.wallpaperengine.weclient)
// Load with: frida -U -f io.wallpaperengine.weclient -l hooks.js

Java.perform(function() {
    console.log("[*] Installing Frida hooks for WE Android app");

    // ---- TcpClient (TCP 7889 pairing + crypto + transfer) ----
    try {
        var TcpClient = Java.use('io.wallpaperengine.weutil.TcpClient');

        TcpClient.performAuthentication.implementation = function(pin, customDeviceName, appVersion, callback) {
            console.log("[TcpClient] performAuthentication:");
            console.log("  pin:              " + pin);
            console.log("  customDeviceName: " + customDeviceName);
            console.log("  appVersion:       " + appVersion);
            return this.performAuthentication(pin, customDeviceName, appVersion, callback);
        };

        try {
            TcpClient.connect.implementation = function() {
                console.log("[TcpClient] connect() called");
                return this.connect();
            };
        } catch (e) { console.log("[TcpClient] connect hook skipped: " + e); }

        try {
            TcpClient.disconnect.implementation = function() {
                console.log("[TcpClient] disconnect() called");
                return this.disconnect();
            };
        } catch (e) { console.log("[TcpClient] disconnect hook skipped: " + e); }
    } catch (e) {
        console.log("[!] TcpClient not loaded yet: " + e);
    }

    // ---- EncAuthRequest constructor + setters ----
    try {
        var EncAuthRequest = Java.use('io.wallpaperengine.weutil.TcpClient$EncAuthRequest');
        EncAuthRequest.$init.implementation = function() {
            this.$init();
            console.log("[EncAuthRequest] created");
        };
        EncAuthRequest.setPin.implementation = function(s) {
            console.log("[EncAuthRequest] pin = " + s);
            return this.setPin(s);
        };
        EncAuthRequest.setMpkgVersion.implementation = function(s) {
            console.log("[EncAuthRequest] mpkgVersion = " + s);
            return this.setMpkgVersion(s);
        };
        EncAuthRequest.setAppVersion.implementation = function(s) {
            console.log("[EncAuthRequest] appVersion = " + s);
            return this.setAppVersion(s);
        };
        EncAuthRequest.setDisplayWidth.implementation = function(i) {
            console.log("[EncAuthRequest] displayWidth = " + i);
            return this.setDisplayWidth(i);
        };
        EncAuthRequest.setDisplayHeight.implementation = function(i) {
            console.log("[EncAuthRequest] displayHeight = " + i);
            return this.setDisplayHeight(i);
        };
    } catch (e) {
        console.log("[!] EncAuthRequest hook skipped: " + e);
    }

    // ---- EncAuthResponse ----
    try {
        var EncAuthResponse = Java.use('io.wallpaperengine.weutil.TcpClient$EncAuthResponse');
        EncAuthResponse.setStatus.implementation = function(s) {
            console.log("[EncAuthResponse] status = " + s);
            return this.setStatus(s);
        };
    } catch (e) {
        console.log("[!] EncAuthResponse hook skipped: " + e);
    }

    // ---- DiscoverService (UDP 7884 discovery) ----
    try {
        var DiscoverService = Java.use('io.wallpaperengine.weclient.DiscoverService');
        DiscoverService.beginDiscovery.implementation = function() {
            console.log("[DiscoverService] beginDiscovery() — UDP 7884 multicast listen");
            return this.beginDiscovery();
        };
    } catch (e) {
        console.log("[!] DiscoverService hook skipped: " + e);
    }

    // ---- TransferService ----
    try {
        var TransferService = Java.use('io.wallpaperengine.weclient.TransferService');
        TransferService.beginPairing.implementation = function(target, uuid, callback) {
            console.log("[TransferService] beginPairing target=" + target
                        + " uuid=" + uuid);
            return this.beginPairing(target, uuid, callback);
        };
    } catch (e) {
        console.log("[!] TransferService hook skipped: " + e);
    }

    // ---- Cipher.init + doFinal (all AES) ----
    try {
        var Cipher = Java.use('javax.crypto.Cipher');
        Cipher.init.overload('int', 'java.security.Key', 'java.security.spec.AlgorithmParameterSpec')
            .implementation = function(mode, key, spec) {
            var modeStr = mode == 1 ? "ENCRYPT" : mode == 2 ? "DECRYPT" : "mode=" + mode;
            var keyBytes = key.getEncoded();
            var keyHex = "";
            for (var i = 0; i < Math.min(keyBytes.length, 32); i++) {
                keyHex += ('0' + (keyBytes[i] & 0xff).toString(16)).slice(-2);
            }
            var ivHex = "";
            try {
                var iv = spec.getIV();
                if (iv) for (var i = 0; i < iv.length; i++) {
                    ivHex += ('0' + (iv[i] & 0xff).toString(16)).slice(-2);
                }
            } catch (e) {}
            console.log("[Cipher] init(" + modeStr + ", key=" + keyHex + " (" + keyBytes.length + "B), iv=" + ivHex + ")");
            return this.init(mode, key, spec);
        };
        Cipher.doFinal.overload('[B').implementation = function(input) {
            var out = this.doFinal(input);
            console.log("[Cipher] doFinal(" + input.length + "B) -> " + out.length + "B");
            // Dump first 64 bytes of input + output as hex for inspection
            function hex(b, max) {
                var s = "";
                for (var i = 0; i < Math.min(b.length, max); i++) {
                    s += ('0' + (b[i] & 0xff).toString(16)).slice(-2);
                }
                return s;
            }
            console.log("  in:  " + hex(input, 64));
            console.log("  out: " + hex(out, 64));
            return out;
        };
    } catch (e) {
        console.log("[!] Cipher hook skipped: " + e);
    }

    // ---- RSAPublicKeyHelper ----
    try {
        var RSAPublicKeyHelper = Java.use('io.wallpaperengine.wedata.RSAPublicKeyHelper');
        RSAPublicKeyHelper.setModulus.implementation = function(bi) {
            var hex = bi.toString(16);
            console.log("[RSA] setModulus bits=" + bi.bitLength()
                        + " hex_first32=" + hex.substring(0, 32) + "...");
            return this.setModulus(bi);
        };
        RSAPublicKeyHelper.setExponent.implementation = function(bi) {
            console.log("[RSA] setExponent hex=" + bi.toString(16));
            return this.setExponent(bi);
        };
    } catch (e) {
        console.log("[!] RSAPublicKeyHelper hook skipped: " + e);
    }

    // ---- SceneLib (native) ----
    try {
        var SceneLib = Java.use('io.wallpaperengine.wrapper.SceneLib');
        SceneLib.getWallpaperType.implementation = function(filePath) {
            var t = this.getWallpaperType(filePath);
            console.log("[SceneLib] getWallpaperType(" + filePath + ") -> " + t);
            return t;
        };
        SceneLib.getWallpaperFileVirtualOffset.implementation = function(filePath) {
            var r = this.getWallpaperFileVirtualOffset(filePath);
            try {
                console.log("[SceneLib] getWallpaperFileVirtualOffset(" + filePath + ") -> vOffset=" + r.getVOffset() + " vSize=" + r.getVSize());
            } catch (e) {
                console.log("[SceneLib] getWallpaperFileVirtualOffset(" + filePath + ") -> null");
            }
            return r;
        };
        SceneLib.enumerateWallpapers.implementation = function() {
            var arr = this.enumerateWallpapers();
            console.log("[SceneLib] enumerateWallpapers() -> " + (arr ? arr.length : 0) + " entries");
            if (arr) {
                for (var i = 0; i < arr.length; i++) {
                    try {
                        console.log("  [" + i + "] title=" + arr[i].getTitle()
                                    + " type=" + arr[i].getType()
                                    + " path=" + arr[i].getFilePath());
                    } catch (e) {}
                }
            }
            return arr;
        };
    } catch (e) {
        console.log("[!] SceneLib hook skipped: " + e);
    }

    // ---- SupportFileLoader (.mpkg VFS reads) ----
    try {
        var SupportFileLoader = Java.use('io.wallpaperengine.weutil.SupportFileLoader');
        SupportFileLoader.loadBitmapFromVFS.implementation = function(vfsSource, offset, size) {
            console.log("[SupportFileLoader] loadBitmapFromVFS(" + vfsSource + ", offset=" + offset + ", size=" + size + ")");
            return this.loadBitmapFromVFS(vfsSource, offset, size);
        };
    } catch (e) {
        console.log("[!] SupportFileLoader hook skipped: " + e);
    }

    console.log("[*] Frida hooks installed. Pair your phone with a PC to capture traffic.");
    console.log("[*] Tip: run 'python we_protocol_capture.py --monitor' alongside this to capture UDP discovery.");
});
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="generate_frida_hooks",
        description="Print/save a Frida hooks script for the WE Android app.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--out", type=Path, default=None,
                       help="Save the hooks script to this path (default: stdout)")
    args = parser.parse_args(argv)
    if args.out:
        args.out.write_text(HOOK_JS, encoding="utf-8")
        print(f"Saved Frida hooks to {args.out}")
        print(f"Load with:")
        print(f"  frida -U -f io.wallpaperengine.weclient -l {args.out}")
        return 0
    print(HOOK_JS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
